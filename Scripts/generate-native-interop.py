#!/usr/bin/env python3
"""Generate explicit unsafe ABI aliases from the pinned Clang inventory."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
FAMILIES = [
    ('Utilities', 'CWaylandUtilities', 'WaylandUtilities'),
    ('Client', 'CWaylandClient', 'WaylandClient'),
    ('Server', 'CWaylandServer', 'WaylandServer'),
    ('Cursor', 'CWaylandCursor', 'WaylandCursor'),
    ('EGL', 'CWaylandEGL', 'WaylandEGL'),
]
REPLACEMENTS = {
    'wl_log_set_handler_client': 'wayland_kit_client_raw_log_handler',
    'wl_log_set_handler_server': 'wayland_kit_server_raw_log_handler',
    'wl_shell_surface_resize': 'wayland_kit_shell_surface_resize',
    'wl_proxy_marshal': 'wl_proxy_marshal_array',
    'wl_proxy_marshal_flags': 'wl_proxy_marshal_array_flags',
    'wl_proxy_marshal_constructor': 'wl_proxy_marshal_array_constructor',
    'wl_proxy_marshal_constructor_versioned': 'wl_proxy_marshal_array_constructor_versioned',
    'wl_resource_post_event': 'wl_resource_post_event_array',
    'wl_resource_queue_event': 'wl_resource_queue_event_array',
    'wl_resource_post_error': 'wayland_kit_resource_error',
    'wl_client_post_implementation_error': 'wayland_kit_client_error',
}
KINDS = {'function':'FunctionDecl', 'record':'RecordDecl', 'enum':'EnumDecl', 'enumMember':'EnumConstantDecl', 'data':'VarDecl', 'type':'TypedefDecl'}

def camel(name):
    parts = name.split('_')
    return ''.join(part[:1].upper() + part[1:] for part in parts if part != 't')

def ast(module):
    source = ROOT / '.build/native-interop' / (module + '.c')
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_text('#include "' + module + '.h"\n')
    command = ['clang', '-I', str(ROOT / 'Sources' / module / 'include'), '-I', str(ROOT / 'Sources/CWaylandRuntime/include'), '-Xclang', '-ast-dump=json', '-fsyntax-only', str(source)]
    tree = json.loads(subprocess.check_output(command, text=True))
    nodes = {}
    def visit(node, enumeration=None):
        if node.get('kind') == 'EnumDecl': enumeration = node.get('name', '')
        if node.get('kind') == 'EnumConstantDecl': node['parentEnumeration'] = enumeration
        kind = node.get('kind'); name = node.get('name','')
        if name.startswith(('wl_', 'WL_', 'WAYLAND_')) and kind in KINDS.values():
            key = kind, name
            if key not in nodes or node.get('completeDefinition'): nodes[key] = node
        for child in node.get('inner',[]): visit(child, enumeration)
    visit(tree)
    return nodes

def unsafe_function(node):
    spellings = [node.get('type',{}).get('qualType','')]
    for child in node.get('inner',[]):
        if child.get('kind') == 'ParmVarDecl': spellings += list(child.get('type',{}).values())
    return any('*' in spelling for spelling in spellings)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    inventory = json.loads((ROOT / 'docs/reference/native-api-coverage.json').read_text())
    families = [(family, module, target, ast(module)) for family,module,target in FAMILIES]
    outputs = {family: ['// Generated by Scripts/generate-native-interop.py. Do not edit.',
                       'import Glibc', 'import ' + module, '',
                       '/// Exposes the pinned native ABI outside all checked ownership guarantees.',
                       '///', '/// Every use requires unsafe acknowledgement. See NativeCompatibility for caller obligations.',
                       '@unsafe public enum ' + family + 'Interop {'] for family,module,target,nodes in families}
    mappings=[]; deferred=[]; macro_cache = {}
    for item in inventory['items']:
        category=item['category']; name=item['name']
        if category in ['protocolMessage','field']: continue
        if category=='macro':
            definition=item['definition']
            if not definition or name in ['WL_EXPORT','WL_DEPRECATED','WL_PRINTF','WL_TYPEOF']:
                mappings.append({'id':item['id'], 'status':'cOnly', 'reason':'C preprocessing/declaration control; no Swift runtime equivalent.'})
                continue
            if name.startswith('wl_'):
                family = 'Server' if name.startswith(('wl_client_', 'wl_resource_')) else 'Utilities'
                mappings.append({'id':item['id'], 'status':'unsafeABI', 'target':'Wayland'+family,
                                 'symbol':family+'Interop.'+name, 'adaptation':'Explicit unsafe native-layout traversal adapter.',
                                 'documentation':'docs/WaylandKit.docc/NativeCompatibility.md'})
                continue
            # Constant macros are resolved in the actual C module, not parsed as Swift expressions.
            candidates=[]
            for family,module,target,nodes in families:
                if module not in macro_cache:
                    macro_cache[module] = subprocess.check_output(['clang','-I',str(ROOT/'Sources'/module/'include'),'-I',str(ROOT/'Sources/CWaylandRuntime/include'),'-dM','-E',str(ROOT/'.build/native-interop'/(module+'.c'))],text=True)
                text = macro_cache[module]
                if re.search(r'^#define '+re.escape(name)+r'(?:\s|$)',text,re.M): candidates.append((family,module,target,None))
        else:
            candidates=[(family,module,target,nodes[(KINDS[category],name)]) for family,module,target,nodes in families if (KINDS[category],name) in nodes]
            if category=='record' and any(node.get('completeDefinition') for _,_,_,node in candidates):
                candidates=[candidate for candidate in candidates if candidate[3].get('completeDefinition')]
        if not candidates: raise RuntimeError('Native declaration has no owning C module: '+name)
        family,module,target,node=candidates[0]
        lines=outputs[family]; member=name
        lines += ['    /// Maps native '+name+' with caller-owned provenance, lifetime, serialization, and cleanup.']
        if category=='function':
            replacement=REPLACEMENTS.get(name,name)
            if replacement!=name: lines += ['    /// Uses '+replacement+' for C ellipsis adaptation or a native C enum/function name collision.']
            if node.get('variadic') and name not in REPLACEMENTS: raise RuntimeError('Unmapped ellipsis: '+name)
            deprecated=any(child.get('kind')=='DeprecatedAttr' for child in node.get('inner',[]))
            if deprecated: lines += ['    @available(*, deprecated, message: "This native compatibility entry point is deprecated by libwayland.")']
            marker='unsafe ' if unsafe_function(node) else ''
            annotation = ''
            lines += ['    public static let '+member+annotation+' = '+marker+module+'.'+replacement]
        elif category=='data':
            interface=name.removesuffix('_interface')
            if family not in ['Client','Server']: raise RuntimeError('Unexpected native data family: '+name)
            lines += ['    public static var '+name+': UnsafePointer<'+module+'.wl_interface> {',
                      '        unsafe '+module+'.wayland_kit_'+family.lower()+'_core_interface("'+interface+'")!', '    }']
        elif category in ['type','record','enum']:
            member=camel(name)
            opaque=category=='record' and not node.get('completeDefinition')
            if opaque:
                member+='Pointer'
                lines += ['    /// This C record is opaque; the alias denotes its pointer handle, not a value layout.']
            native='OpaquePointer' if opaque else ('@convention(c) (UnsafePointer<CChar>?, UnsafeMutableRawPointer?) -> Void' if name == 'wl_log_func_t' else module+'.'+name)
            if name == 'wl_log_func_t': lines += ['    /// The callback receives an opaque borrowed va_list scope; native formatting uses an explicit C va_copy bridge.']
            lines += ['    public typealias '+member+' = '+native]
        else:
            lines += ['    public static let '+member+' = '+module+'.'+name]
        mappings.append({'id':item['id'], 'status':'unsafeABI', 'target':target, 'symbol':family+'Interop.'+member,
                         'adaptation':('Opaque callback-scoped va_list bridge; formatting uses C va_copy.' if name == 'wl_log_func_t' else REPLACEMENTS.get(name)), 'documentation':'docs/WaylandKit.docc/NativeCompatibility.md'})
    for item in inventory['items']:
        if item['category'] != 'field': continue
        record, field = item['name'].split('.', 1)
        parent = next(mapping for mapping in mappings if mapping['id'] == 'c.record.' + record)
        mappings.append({'id':item['id'], 'status':'unsafeABI', 'target':parent['target'],
                         'symbol':parent['symbol']+'.'+field, 'adaptation':'Imported native field through explicit C record alias; no layout transformation.',
                         'documentation':'docs/WaylandKit.docc/NativeCompatibility.md'})
    for family,module,target,nodes in families:
        content='\n'.join(outputs[family]+['}'])+'\n'
        path=ROOT/'Sources'/target/'NativeInterop.swift'
        if arguments.check:
            if path.read_text()!=content: raise RuntimeError('Generated native output differs: '+str(path))
        else:path.write_text(content)
    report={'headers':inventory['headers'],'baseline':inventory['baseline'],'mappings':mappings,'deferred':deferred,
            'note':'Unsafe ABI availability is distinct from high-level ownership and per-native-branch runtime acceptance.'}
    path=ROOT/'docs/reference/native-interop-manifest.json';content=json.dumps(report,indent=2)+'\n'
    if arguments.check:
        if path.read_text()!=content:raise RuntimeError('Generated native manifest differs.')
    else:path.write_text(content)
    print('Verified' if arguments.check else 'Generated',len(mappings),'explicit native mappings;',len(deferred),'macro adapters remain.')
if __name__=='__main__':main()
